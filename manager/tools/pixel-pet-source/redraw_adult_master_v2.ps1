function Get-V2Stencil([string]$species, [string]$view) {
    $value = $v2Stencils[$species][$view]
    if ([string]::IsNullOrWhiteSpace($value)) { throw "Missing V2 stencil: $species/$view" }
    return $value
}

function Draw-V2IdleDetail([hashtable]$art, [string]$species, [int]$facing, [int]$frame) {
    $rhythm = @(0, 1, 2, 1, 0, -1, -2, -1)[$frame % 8]
    switch ($species) {
        "cat" {
            $origin = if ($facing -eq 2) { 25 } elseif ($facing -eq 3) { 6 } else { 25 }
            Draw-V2Line $art $origin 22 ($origin + [Math]::Sign($rhythm) * 2) (19 - [Math]::Abs($rhythm)) 1
            Set-V2Pixel $art ($origin + [Math]::Sign($rhythm) * 2) (19 - [Math]::Abs($rhythm)) 2
        }
        "dog" {
            $origin = if ($facing -eq 2) { 26 } elseif ($facing -eq 3) { 5 } else { 25 }
            Draw-V2Line $art $origin 24 ($origin + [Math]::Sign($rhythm) * 2) (24 + $rhythm) 1
            Set-V2Pixel $art ($origin + [Math]::Sign($rhythm) * 2) (24 + $rhythm) 2
        }
        "bird" {
            $wingY = 20 + $rhythm
            Draw-V2Line $art 10 21 6 $wingY 1
            Draw-V2Line $art 22 21 26 (20 - $rhythm) 1
            Set-V2Pixel $art 6 $wingY 3
            Set-V2Pixel $art 26 (20 - $rhythm) 3
        }
        "rabbit" {
            $earSweep = @(-3, -2, -1, 0, 1, 2, 3, 2)[$frame % 8]
            Draw-V2Line $art 11 20 (11 + $earSweep) (15 + [Math]::Abs($earSweep % 2)) 1
            Draw-V2Line $art 21 20 (21 - $earSweep) (15 + [Math]::Abs($earSweep % 2)) 1
        }
        "penguin" {
            Draw-V2Line $art 10 20 7 (22 + $rhythm) 1
            Draw-V2Line $art 22 20 25 (22 - $rhythm) 1
        }
    }
}

function Draw-V2WalkDetail([hashtable]$art, [string]$species, [int]$facing, [int]$frame) {
    $stride = @(-3, -2, -1, 1, 3, 2, 1, -1, -3, -2)[$frame]
    $lead = [Math]::Sign($stride)
    $cadence = @(-4, -3, -2, -1, 0, 1, 2, 3, 4, 3)[$frame]
    if ($species -in @("bird", "penguin")) {
        Set-V2Pixel $art (12 + $lead) (29 - [Math]::Abs([Math]::Min(0, $stride))) 6
        Set-V2Pixel $art (19 + $lead) (29 - [Math]::Abs([Math]::Max(0, $stride))) 6
    } else {
        Draw-V2Line $art 12 27 (10 + $lead * 2) (29 - [Math]::Abs([Math]::Min(0, $stride))) 1
        Draw-V2Line $art 20 27 (22 + $lead * 2) (29 - [Math]::Abs([Math]::Max(0, $stride))) 1
    }
    switch ($species) {
        "cat" { Draw-V2Line $art 24 22 (27 - $lead) (20 - [Math]::Abs($stride)) 1 }
        "dog" { Draw-V2Line $art 25 24 (28 - $lead) (25 + $lead) 1 }
        "bird" {
            Draw-V2Line $art 10 21 (6 + $cadence) (24 - [Math]::Abs($cadence % 3)) 1
            Set-V2Pixel $art (7 + $cadence) (24 - [Math]::Abs($cadence % 3)) 3
        }
        "rabbit" { Draw-V2Line $art 11 10 (9 + $lead) (5 + [Math]::Abs($stride)) 1 }
        "penguin" {
            Draw-V2Line $art 10 20 (6 + $cadence) (24 - [Math]::Abs($cadence % 3)) 1
            Draw-V2Line $art 22 20 (26 - $cadence) (24 - [Math]::Abs($cadence % 2)) 1
            Set-V2Pixel $art (7 + $cadence) (24 - [Math]::Abs($cadence % 3)) 3
            Set-V2Pixel $art (25 - $cadence) (24 - [Math]::Abs($cadence % 2)) 3
        }
    }
}

function Draw-V2EatingDetail([hashtable]$art, [string]$species, [int]$facing, [int]$frame) {
    $reach = @(-4, -3, -2, -1, 0, 1, 2, 3, 4, 3)[$frame]
    $mouthX = if ($facing -eq 2) { 9 } elseif ($facing -eq 3) { 22 } else { 17 }
    $direction = if ($facing -eq 3) { 1 } else { -1 }
    # Food travels through eight exterior positions into the beak/paw. Keeping
    # it outside the broad adult silhouette preserves the action at card scale.
    $foodX = if ($facing -eq 3) { 30 - $frame } else { 1 + $frame }
    $foodY = @(19, 18, 17, 16, 15, 14, 13, 12, 13, 14)[$frame]
    Set-V2Pixel $art $foodX $foodY 6
    Set-V2Pixel $art ($foodX + $direction) $foodY 5
    Draw-V2Line $art (16 + $direction * ($frame % 2)) 24 $foodX ($foodY + 1) 4
    # The feeding limb follows the food in a full reach-and-return cycle.
    # This keeps the motion readable after 32px integer scaling.
    $handBaseX = if ($species -in @("bird", "penguin")) { 18 } else { 17 }
    $handBaseY = if ($species -eq "penguin") { 24 } else { 25 }
    Draw-V2Line $art $handBaseX $handBaseY ($handBaseX + $reach) (20 + [Math]::Abs($reach % 3)) 1
    Set-V2Pixel $art ($handBaseX + $reach) (20 + [Math]::Abs($reach % 3)) 3
    if ($species -eq "bird") { Set-V2Pixel $art ($mouthX + $direction) 15 6 }
}

function Draw-V2SleepDetail([hashtable]$art, [string]$species, [int]$facing, [int]$frame) {
    $dreamX = if ($facing -eq 2) { 19 } elseif ($facing -eq 3) { 9 } else { 23 }
    $dreamY = 15 - [Math]::Floor($frame / 2)
    $breath = @(0, 1, 2, 3, 2, 1, 0, -1, -2, -1)[$frame]
    Set-V2Pixel $art $dreamX $dreamY 5
    Set-V2Pixel $art ($dreamX + 1) ($dreamY - 1) 5
    if ($frame % 3 -eq 0) { Set-V2Pixel $art ($dreamX + 2) ($dreamY - 2) 5 }
    # A sleeping pose still moves its body: this is a breathing limb/tail cycle,
    # not a decorative particle animation.
    switch ($species) {
        "cat" { Draw-V2Line $art 21 25 (24 + $breath) (25 - [Math]::Abs($breath % 2)) 1 }
        "dog" { Draw-V2Line $art 20 25 (24 + $breath) (26 - [Math]::Abs($breath % 2)) 1 }
        "bird" { Draw-V2Line $art 13 24 (10 + $breath) (25 - [Math]::Abs($breath % 2)) 1 }
        "rabbit" { Draw-V2Line $art 12 22 (10 + $breath) (19 - [Math]::Abs($breath % 2)) 1 }
        "penguin" { Draw-V2Line $art 13 25 (10 + $breath) (26 - [Math]::Abs($breath % 2)) 1 }
    }
}

function Draw-AdultFrame([string]$species, [int]$action, [int]$facing, [int]$frame) {
    $art = New-V2Art
    if ($facing -eq 3) {
        $art = Draw-AdultFrame $species $action 2 $frame
        return Mirror-V2Art $art
    }
    $view = if ($action -eq 4) { "sleep" } elseif ($facing -eq 0) { "front" } elseif ($facing -eq 1) { "back" } else { "side" }
    Paint-V2Stencil $art (Get-V2Stencil $species $view)
    switch ($action) {
        0 { Draw-V2IdleDetail $art $species $facing $frame }
        1 { Draw-V2WalkDetail $art $species $facing $frame }
        2 { Draw-V2EatingDetail $art $species $facing $frame }
        4 { Draw-V2SleepDetail $art $species $facing $frame }
    }
    return Expand-V2Art $art
}

foreach ($species in $speciesNames) {
    $imagePath = Join-Path $SourceDirectory "$species.png"
    $anchorsPath = Join-Path $SourceDirectory "$species.anchors.json"
    $bytes = Load-BitmapBytes $imagePath
    $anchors = @(Get-Content -Raw -LiteralPath $anchorsPath | ConvertFrom-Json)
    foreach ($action in $coreActions) {
        for ($facing = 0; $facing -lt 4; $facing++) {
            for ($frame = 0; $frame -lt $actionFrameCounts[$action]; $frame++) {
                $art = Draw-AdultFrame $species $action $facing $frame
                $index = Get-FrameIndex $action $facing $frame
                Write-Art $bytes $index $art
                $frameAnchors = Get-AdultAnchors $art $species $action $facing $frame
                if ($action -eq 4) {
                    $sleepHandShift = @(-2, -1, 0, 1, 2, 1, 0, -1, -2, -1)[$frame]
                    $frameAnchors.hand[0] = Clamp-Grid ($frameAnchors.hand[0] + $sleepHandShift)
                    $frameAnchors.hand[1] = Clamp-Grid ($frameAnchors.hand[1] - [Math]::Abs($sleepHandShift % 2))
                }
                $anchors[$index] = [PSCustomObject]@{
                    index = $index
                    anchors = $frameAnchors
                }
            }
        }
    }
    Save-BitmapBytes $imagePath $bytes
    [System.IO.File]::WriteAllText($anchorsPath, ($anchors | ConvertTo-Json -Depth 5), [System.Text.UTF8Encoding]::new($false))
    Write-Output "Redrew adult master v2 for $species"
}

