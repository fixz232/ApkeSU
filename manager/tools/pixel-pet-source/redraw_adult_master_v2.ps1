$v2ColorCodes = @{
    o = 1; b = 2; s = 3; c = 4; h = 5; a = 6; m = 7; r = 8; e = 9; x = 10
}

function New-V2Art { @{} }

function Set-V2Pixel([hashtable]$art, [int]$x, [int]$y, [int]$color) {
    if ($x -ge 0 -and $x -lt 32 -and $y -ge 0 -and $y -lt 32) {
        $art["$x,$y"] = $color
    }
}

function Clear-V2Pixel([hashtable]$art, [int]$x, [int]$y) {
    [void]$art.Remove("$x,$y")
}

function Draw-V2Line([hashtable]$art, [int]$x0, [int]$y0, [int]$x1, [int]$y1, [int]$color) {
    $steps = [Math]::Max([Math]::Abs($x1 - $x0), [Math]::Abs($y1 - $y0))
    for ($step = 0; $step -le $steps; $step++) {
        $fraction = if ($steps -eq 0) { 0.0 } else { $step / [double]$steps }
        Set-V2Pixel $art ([Math]::Round($x0 + ($x1 - $x0) * $fraction)) ([Math]::Round($y0 + ($y1 - $y0) * $fraction)) $color
    }
}

function Paint-V2Stencil([hashtable]$art, [string]$source, [int]$originX = 3, [int]$originY = 15) {
    $rows = $source.Trim().Split("`n") | ForEach-Object { $_.TrimEnd("`r") }
    if ($rows.Count -gt 29 -or ($rows | Measure-Object Length -Maximum).Maximum -gt 26) {
        throw "Adult master stencil exceeds its 26x29 canvas"
    }
    for ($y = 0; $y -lt $rows.Count; $y++) {
        $row = $rows[$y]
        for ($x = 0; $x -lt $row.Length; $x++) {
            $code = $v2ColorCodes[$row[$x].ToString()]
            if ($null -ne $code) { Set-V2Pixel $art ($originX + $x) ($originY + $y) $code }
        }
    }
}

function Get-V2PixelPriority([int]$color) {
    switch ($color) {
        1 { return 100 } # Outline must survive a scale collision.
        9 { return 90 }
        10 { return 90 }
        6 { return 80 }
        5 { return 70 }
        4 { return 60 }
        3 { return 50 }
        default { return 40 }
    }
}

function Expand-V2Art([hashtable]$art) {
    $expanded = New-V2Art
    foreach ($cell in $art.GetEnumerator()) {
        $point = $cell.Key.Split(',')
        $x = [int]$point[0]
        $y = [int]$point[1]
        # Expand from the atlas pivot and preserve the authored foot baseline.
        $targetX = [Math]::Round(16 + ($x - 16) * 1.35)
        $targetY = [Math]::Round(29 + ($y - 29) * 1.12)
        $key = "$targetX,$targetY"
        if (-not $expanded.ContainsKey($key) -or (Get-V2PixelPriority $cell.Value) -ge (Get-V2PixelPriority $expanded[$key])) {
            Set-V2Pixel $expanded $targetX $targetY ([int]$cell.Value)
        }
    }
    return $expanded
}

function Mirror-V2Art([hashtable]$art) {
    $result = New-V2Art
    foreach ($cell in $art.GetEnumerator()) {
        $point = $cell.Key.Split(',')
        Set-V2Pixel $result (31 - [int]$point[0]) ([int]$point[1]) ([int]$cell.Value)
    }
    return $result
}

